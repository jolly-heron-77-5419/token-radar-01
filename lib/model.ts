// The token radar's model, version radar-2: one snapshot of the protocol universe in, one ranked
// board out. Written for this entry from the sealed snapshot's own figures; no protocol name is ever
// special-cased, and the same functions score every row.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds every
// other rankable pre-token protocol below the floor: the early rows the radar exists to find. A
// protocol is pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol);
// a protocol is rankable when it is pre-token and not a wrapped, staked or bridged product of a token
// that already trades (no Bridge, Canonical Bridge, Liquid Staking, Liquid Restaking, Restaked BTC or
// CEX category, no wrapped/staked/staking word in its name, no exchange prefix, no version marker).
// The snapshot's live-token protocols are kept apart and shown with the market's own values, never
// mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, in four factors:
//
//   category multiple  the median market-cap-to-TVL ratio of the live (token-trading) protocols in
//                       the same category, read off this very snapshot; 0.05..0.60, falling back to
//                       the snapshot-wide median when a category has fewer than three live samples.
//   growth              1 + clamp(change_7d, -60, 120) / 100 * 0.6
//   maturity            0.7 + min(age_days, 1095) / 1095 * 0.5   (age unknown: 365 days)
//   breadth             1 + 0.02 * min(chains.length, 10)
//
//   implied = tvl_usd * category_multiple * growth * maturity * breadth
//
// The category multiple is the model's answer to "what is a dollar of TVL worth here": a DEX dollar
// and a lending dollar do not price the same, and the snapshot's own live protocols say by how much.
// Growth rewards momentum, maturity rewards a long tokenless run (a protocol listed years ago with no
// token is further along the road to one), breadth rewards a protocol live on many chains. A board
// ranked this way is not a TVL table: the multiple, the growth and the maturity reorder it.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

